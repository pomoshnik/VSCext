using Avalonia.Controls;
using OneC.Core;

namespace Client;

/// <summary>Помеченный на удаление объект (элемент справочника или документ).</summary>
public record ПомеченныйОбъект(ОбъектМетаданных Объект, string Ссылка, string Представление);

/// <summary>Итог попытки удаления: либо удалён, либо список мест, где на объект ссылаются.</summary>
public record РезультатУдаления(ПомеченныйОбъект Объект, bool Удалён, List<string> Препятствия);

/// <summary>
/// «Удаление помеченных объектов» — как одноимённая операция в 1С:
/// физически удаляются только объекты, на которые нет ссылок из других данных
/// (реквизиты объектов, табличные части, записи регистров). Собственные строки
/// удаляемого объекта (его табличные части и движения) препятствием не считаются.
/// </summary>
public static class СервисУдаленияПомеченных
{
    /// <summary>Все помеченные на удаление объекты базы.</summary>
    public static List<ПомеченныйОбъект> Найти(База база, Конфигурация конфиг)
    {
        var список = new List<ПомеченныйОбъект>();
        foreach (var о in конфиг.Объекты.Where(о => о.Вид is "Справочник" or "Документ"))
        {
            if (о.Таблица == null || !база.ТаблицаЕсть(о.Таблица)) continue;
            foreach (var строка in база.Выбрать(о.Таблица))
            {
                if (!Флаг(строка, "ПометкаУдаления")) continue;
                список.Add(new ПомеченныйОбъект(о, строка.GetValueOrDefault("Ссылка")?.ToString() ?? "",
                    Представление(о, строка)));
            }
        }
        return список;
    }

    /// <summary>Где на объект ссылаются другие данные (пусто — удалять можно).</summary>
    public static List<string> НайтиСсылки(База база, Конфигурация конфиг, ПомеченныйОбъект п)
    {
        var тип = (п.Объект.Вид == "Справочник" ? "СправочникСсылка." : "ДокументСсылка.") + п.Объект.Имя;
        var препятствия = new List<string>();

        foreach (var о in конфиг.Объекты)
        {
            Проверить(о.Таблица, о.Представление, о.Реквизиты.Concat(о.Измерения).Concat(о.Ресурсы));
            foreach (var тч in о.ТабличныеЧасти)
                Проверить(тч.Таблица, $"{о.Представление} ({тч.Имя})", тч.Реквизиты);
        }
        return препятствия;

        void Проверить(string? таблица, string где, IEnumerable<Реквизит> поля)
        {
            if (таблица == null || !база.ТаблицаЕсть(таблица)) return;
            foreach (var поле in поля.Where(ф => ф.Тип == тип))
            {
                // строки самого удаляемого объекта (его ТЧ — «Ссылка», его движения — «Регистратор»)
                // исчезнут вместе с ним и удалению не мешают
                var чужие = база.Строки(таблица, поле.Имя, п.Ссылка).Count(с =>
                    (с.GetValueOrDefault("Ссылка") ?? с.GetValueOrDefault("Регистратор"))?.ToString() != п.Ссылка);
                if (чужие > 0) препятствия.Add($"{где}, поле «{поле.Имя}» — записей: {чужие}");
            }
        }
    }

    /// <summary>
    /// Удаляет всё, на что нет ссылок. Проходы повторяются, пока есть прогресс:
    /// цепочка «помеченный документ ссылается на помеченный справочник» удаляется целиком.
    /// </summary>
    public static List<РезультатУдаления> Удалить(База база, Конфигурация конфиг, List<ПомеченныйОбъект> помеченные)
    {
        var осталось = new List<ПомеченныйОбъект>(помеченные);
        var удалённые = new List<ПомеченныйОбъект>();
        for (var прогресс = true; прогресс && осталось.Count > 0;)
        {
            прогресс = false;
            foreach (var п in осталось.ToList())
            {
                if (НайтиСсылки(база, конфиг, п).Count > 0) continue;
                УдалитьФизически(база, п);
                осталось.Remove(п);
                удалённые.Add(п);
                прогресс = true;
            }
        }
        var итог = удалённые.Select(п => new РезультатУдаления(п, true, new List<string>())).ToList();
        итог.AddRange(осталось.Select(п => new РезультатУдаления(п, false, НайтиСсылки(база, конфиг, п))));
        return итог;
    }

    static void УдалитьФизически(База база, ПомеченныйОбъект п)
    {
        база.Удалить(п.Объект.Таблица!, "Ссылка", п.Ссылка);
        foreach (var тч in п.Объект.ТабличныеЧасти.Where(т => т.Таблица != null))
            база.Удалить(тч.Таблица!, "Ссылка", п.Ссылка);
        if (п.Объект.Вид == "Документ") база.УдалитьДвижения(п.Ссылка);
    }

    static string Представление(ОбъектМетаданных о, Dictionary<string, object?> строка) =>
        о.Вид == "Документ"
            ? $"{о.Представление} № {строка.GetValueOrDefault("Номер")} от {строка.GetValueOrDefault("Дата")}"
            : $"{о.Представление}: {строка.GetValueOrDefault("Наименование")}";

    static bool Флаг(Dictionary<string, object?> строка, string имя) =>
        строка.TryGetValue(имя, out var з) && з?.ToString() is "1" or "True" or "true";
}

/// <summary>Окно «Удаление помеченных объектов»: список помеченных, удаление, отчёт о причинах отказа.</summary>
public class ОкноУдаленияПомеченных : Window
{
    public ОкноУдаленияПомеченных(База база, Конфигурация конфиг)
    {
        Title = "Удаление помеченных объектов";
        Width = 640;
        SizeToContent = SizeToContent.Height;
        MaxHeight = 640;
        WindowStartupLocation = WindowStartupLocation.CenterOwner;

        var панель = Шаблон.ПанельФормы();
        var список = new StackPanel { Spacing = 2 };
        var итог = new StackPanel { Spacing = 2 };

        Button кнУдалить = null!;
        кнУдалить = Шаблон.Кнопка("Удалить", () =>
        {
            итог.Children.Clear();
            var результаты = СервисУдаленияПомеченных.Удалить(база, конфиг,
                СервисУдаленияПомеченных.Найти(база, конфиг));
            foreach (var р in результаты)
            {
                итог.Children.Add(new TextBlock
                {
                    Text = (р.Удалён ? "✔ Удалён: " : "✘ Не удалён: ") + р.Объект.Представление,
                    FontWeight = Avalonia.Media.FontWeight.SemiBold
                });
                foreach (var причина in р.Препятствия)
                    итог.Children.Add(new TextBlock { Text = "        ссылки: " + причина });
            }
            Обновить();
        }, основная: true);

        void Обновить()
        {
            список.Children.Clear();
            var помеченные = СервисУдаленияПомеченных.Найти(база, конфиг);
            foreach (var п in помеченные)
            {
                var строка = new StackPanel { Orientation = Avalonia.Layout.Orientation.Horizontal, Spacing = 6 };
                строка.Children.Add(Шаблон.ИконкаСтроки(п.Объект.Вид, false, true));
                строка.Children.Add(new TextBlock
                {
                    Text = п.Представление,
                    VerticalAlignment = Avalonia.Layout.VerticalAlignment.Center
                });
                список.Children.Add(строка);
            }
            if (помеченные.Count == 0)
                список.Children.Add(new TextBlock { Text = "Помеченных на удаление объектов нет." });
            кнУдалить.IsEnabled = помеченные.Count > 0;
        }

        панель.Children.Add(new TextBlock
        {
            Text = "Будут удалены только объекты, на которые нет ссылок из других данных.",
            TextWrapping = Avalonia.Media.TextWrapping.Wrap
        });
        панель.Children.Add(список);
        панель.Children.Add(итог);
        панель.Children.Add(Шаблон.ПанельКнопокСправа(кнУдалить, Шаблон.Кнопка("Закрыть", () => Close())));
        Content = new ScrollViewer { Content = панель };
        Обновить();
    }
}
