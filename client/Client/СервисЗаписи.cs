using OneC.Core;

namespace Client;

/// <summary>
/// Конвейер чтения и записи объектов — общий для генерируемых форм (РедакторЗаписи)
/// и произвольных AXAML-форм из конфигурации (IПроизвольнаяФорма).
/// </summary>
public static class СервисЗаписи
{
    /// <summary>Читает запись из строки списка (поля + табличные части) либо создаёт новую (ПриЗаполнении).</summary>
    public static ЗаписьОбъекта Прочитать(База база, ОбъектМетаданных объект, Dictionary<string, object?>? строка)
    {
        var запись = new ЗаписьОбъекта { ПолноеИмяОбъекта = объект.ПолноеИмя };

        if (строка == null)
        {
            РеестрМодулей.Найти(объект.ПолноеИмя)?.ПриЗаполнении(запись);
            // как в 1С: у нового документа дата заполняется текущей
            if (объект.Вид == "Документ" && string.IsNullOrEmpty(запись.Строка("Дата")))
                запись["Дата"] = DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss");
            return запись;
        }

        запись.Ссылка = строка.GetValueOrDefault("Ссылка")?.ToString();
        foreach (var (имя, значение) in строка) запись[имя] = значение;

        if (запись.Ссылка != null)
            foreach (var тч in объект.ТабличныеЧасти)
                if (!string.IsNullOrEmpty(тч.Таблица))
                    запись.ТабличныеЧасти[тч.Имя] =
                        база.Строки(тч.Таблица, "Ссылка", запись.Ссылка, "НомерСтроки");
        return запись;
    }

    /// <summary>
    /// Записывает объект через полный конвейер платформы:
    /// ПередЗаписью → ОбработкаПроведения → автонумерация → поля + табличные части + движения → ПриЗаписи.
    /// При установленном отказе в базе ничего не меняется.
    /// </summary>
    public static Отказ Записать(База база, ОбъектМетаданных объект, ЗаписьОбъекта запись, bool провести)
    {
        var отказ = new Отказ();
        var модуль = РеестрМодулей.Найти(объект.ПолноеИмя);

        // --- Бизнес-логика: ПередЗаписью ---
        модуль?.ПередЗаписью(запись, отказ);
        if (отказ.Значение) return отказ;

        // --- Проведение: движения формируются ДО записи — при отказе ничего не меняется ---
        var движения = new НаборДвижений();
        if (объект.Вид == "Документ" && провести)
        {
            модуль?.ОбработкаПроведения(запись, движения, отказ);
            if (отказ.Значение) return отказ;
        }

        var поля = new Dictionary<string, object?>(запись.Поля);
        поля["Ссылка"] = запись.Ссылка ?? Guid.NewGuid().ToString();

        // Автонумерация кода/номера
        var таблица = База.ИмяТаблицы(объект);
        if (объект.Вид == "Справочник" && string.IsNullOrWhiteSpace(поля.GetValueOrDefault("Код")?.ToString()))
            поля["Код"] = (база.Количество(таблица) + 1).ToString("D9");
        if (объект.Вид == "Документ" && string.IsNullOrWhiteSpace(поля.GetValueOrDefault("Номер")?.ToString()))
            поля["Номер"] = (база.Количество(таблица) + 1).ToString("D9");
        if (объект.Вид == "Документ" && string.IsNullOrWhiteSpace(поля.GetValueOrDefault("Дата")?.ToString()))
            поля["Дата"] = DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss");
        if (объект.Вид == "Документ")
            поля["Проведен"] = провести ? 1 : 0;

        база.Записать(таблица, поля);
        запись.Ссылка = поля["Ссылка"]!.ToString();

        var ссылкаВладельца = запись.Ссылка!;
        foreach (var тч in объект.ТабличныеЧасти)
        {
            if (string.IsNullOrEmpty(тч.Таблица)) continue;
            var строкиТч = new List<Dictionary<string, object?>>();
            int номер = 1;
            foreach (var строкаТч in запись.Строки(тч.Имя))
                строкиТч.Add(new Dictionary<string, object?>(строкаТч)
                {
                    ["Ссылка"] = ссылкаВладельца,
                    ["НомерСтроки"] = номер++
                });
            база.ЗаписатьСтроки(тч.Таблица, ссылкаВладельца, строкиТч);
        }

        // --- Движения по регистрам накопления ---
        if (объект.Вид == "Документ")
        {
            if (провести)
                база.ЗаписатьДвижения(ссылкаВладельца, поля.GetValueOrDefault("Дата")?.ToString() ?? "", движения);
            else
                база.УдалитьДвижения(ссылкаВладельца); // запись без проведения = снятие с проведения
        }

        модуль?.ПриЗаписи(запись);
        return отказ;
    }
}
