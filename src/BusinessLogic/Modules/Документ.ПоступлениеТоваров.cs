using OneC.Core;

namespace BusinessLogic.Modules;

[МодульОбъекта("Документ.ПоступлениеТоваров")]
public class Документ_ПоступлениеТоваров : МодульДокументПоступлениеТоваров
{
    public override void ПередЗаписью(ДокументПоступлениеТоваровЗапись запись, Отказ отказ)
    {
        if (string.IsNullOrWhiteSpace(запись.Контрагент))
            отказ.Установить("Не выбран контрагент.");

        if (запись.СуммаДокумента < 0)
            отказ.Установить("Сумма документа не может быть отрицательной.");
    }

    public override void ПриЗаполнении(ДокументПоступлениеТоваровЗапись запись)
    {
        запись.Дата = DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss");
    }

    // Команда формы (кнопка «Заполнить цены и суммы» в дизайнере форм):
    // подставляет цену из справочника и пересчитывает суммы строк и итог документа
    public void ЗаполнитьСуммы(ДокументПоступлениеТоваровЗапись запись)
    {
        decimal итог = 0;
        foreach (var строка in запись.Товары)
        {
            if (строка.Цена == 0 && !string.IsNullOrEmpty(строка.Номенклатура))
            {
                var номенклатура = Справочники.Номенклатура
                    .Отбор("Ссылка", строка.Номенклатура)
                    .ВыбратьПервую();
                if (номенклатура != null) строка.Цена = номенклатура.Цена;
            }
            строка.Сумма = строка.Количество * строка.Цена;
            итог += строка.Сумма;
        }
        запись.СуммаДокумента = итог;
    }

    // Проведение: по каждой строке ТЧ «Товары» — приход в регистр «ОстаткиТоваров»
    public override void ОбработкаПроведения(ДокументПоступлениеТоваровЗапись запись, Движения движения, Отказ отказ)
    {
        if (string.IsNullOrWhiteSpace(запись.Склад))
        {
            отказ.Установить("Для проведения выберите склад.");
            return;
        }
        if (запись.Товары.Count == 0)
        {
            отказ.Установить("Табличная часть «Товары» пуста — проводить нечего.");
            return;
        }

        foreach (var строка in запись.Товары)
        {
            if (строка.Количество <= 0)
            {
                отказ.Установить($"Количество должно быть больше нуля (строка с номенклатурой «{строка.Номенклатура}»).");
                continue;
            }
            var движение = движения.ОстаткиТоваров.ДобавитьПриход();
            движение.Номенклатура = строка.Номенклатура;
            движение.Склад = запись.Склад;
            движение.Количество = строка.Количество;
        }
    }
}
