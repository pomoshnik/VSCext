using OneC.Core;

namespace BusinessLogic.Modules;

[МодульОбъекта("Документ.ПоступлениеТоваров")]
public class Документ_ПоступлениеТоваров : МодульОбъекта
{
    public override void ПередЗаписью(ЗаписьОбъекта запись, Отказ отказ)
    {
        if (string.IsNullOrWhiteSpace(запись.Строка("Контрагент")))
            отказ.Установить("Не выбран контрагент.");

        if (запись.Число("СуммаДокумента") < 0)
            отказ.Установить("Сумма документа не может быть отрицательной.");
    }

    public override void ПриЗаполнении(ЗаписьОбъекта запись)
    {
        запись["Дата"] = DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss");
    }
}
