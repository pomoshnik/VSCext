using OneC.Core;

namespace BusinessLogic.Modules;

[МодульОбъекта("Справочник.Контрагенты")]
public class Справочник_Контрагенты : МодульСправочникКонтрагенты
{
    public override void ПередЗаписью(СправочникКонтрагентыЗапись запись, Отказ отказ)
    {
        if (string.IsNullOrWhiteSpace(запись.Наименование))
            отказ.Установить("Не заполнено наименование контрагента.");

        var инн = запись.ИНН.Trim();
        if (инн.Length > 0 && инн.Length != 10 && инн.Length != 12)
            отказ.Установить("ИНН должен содержать 10 или 12 цифр.");
        if (инн.Length > 0 && !инн.All(char.IsDigit))
            отказ.Установить("ИНН должен состоять только из цифр.");
    }
}
