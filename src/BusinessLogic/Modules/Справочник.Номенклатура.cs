using OneC.Core;

namespace BusinessLogic.Modules;

/// <summary>
/// Модуль объекта: Справочник.Номенклатура
/// Реквизиты доступны через точку, с автодополнением:
/// типы генерируются публикатором в Generated/Метаданные.g.cs
/// </summary>
[МодульОбъекта("Справочник.Номенклатура")]
public class Справочник_Номенклатура : МодульСправочникНоменклатура
{
    public override void ПередЗаписью(СправочникНоменклатураЗапись запись, Отказ отказ)
    {
        if (string.IsNullOrWhiteSpace(запись.Наименование))
            отказ.Установить("Не заполнено наименование номенклатуры.");

        if (string.IsNullOrWhiteSpace(запись.Артикул))
            отказ.Установить("Поле «Артикул» обязательно для заполнения.");

        if (запись.Цена < 0)
            отказ.Установить("Цена не может быть отрицательной.");
    }

    public override void ПриЗаполнении(СправочникНоменклатураЗапись запись)
    {
        запись.ЕдиницаИзмерения = "шт";
        запись.СтавкаНДС = Перечисления.СтавкиНДС.НДС20;
    }
}
