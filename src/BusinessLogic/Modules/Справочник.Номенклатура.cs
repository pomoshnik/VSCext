using OneC.Core;

namespace BusinessLogic.Modules;

/// <summary>
/// Модуль объекта: Справочник.Номенклатура
/// Обработчики событий в стиле 1С: ПередЗаписью, ПриЗаписи, ПриЗаполнении.
/// </summary>
[МодульОбъекта("Справочник.Номенклатура")]
public class Справочник_Номенклатура : МодульОбъекта
{
    public override void ПередЗаписью(ЗаписьОбъекта запись, Отказ отказ)
    {
        if (string.IsNullOrWhiteSpace(запись.Строка("Наименование")))
            отказ.Установить("Не заполнено наименование номенклатуры.");

        if (string.IsNullOrWhiteSpace(запись.Строка("Артикул")))
            отказ.Установить("Поле «Артикул» обязательно для заполнения.");

        if (запись.Число("Цена") < 0)
            отказ.Установить("Цена не может быть отрицательной.");
    }

    public override void ПриЗаполнении(ЗаписьОбъекта запись)
    {
        запись["ЕдиницаИзмерения"] = "шт";
        запись["СтавкаНДС"] = "НДС20";
    }
}
